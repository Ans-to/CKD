"""Local-LLM script generation (optional, offline).

The model is asked for strict JSON matching our scene schema.  Output is parsed
with `extract_json`, repaired where possible, then *validated*; invalid output is
rejected (never rendered blind).  If the model cannot produce both requested
languages the run fails with a clear message instead of mixing languages.

This path was NOT executed in the development sandbox (no GGUF weights could be
downloaded there because only GitHub hosts are reachable).  It is therefore
marked "experimental / untested" in the UI and docs.
"""
from __future__ import annotations

import json
from typing import Any, Dict, List, Sequence

from .schema import Scene, Story, StoryValidationError, extract_json, validate_story

PROMPT = """You write short explanatory videos. Return ONLY JSON, no prose.

Schema:
{{
  "title": {{"en": str, "ur": str}},
  "scenes": [
    {{
      "id": "short_slug",
      "purpose": "hook|explain|example|recap|cta",
      "motif": "flow|cycle|compare|layers|structure|scale",
      "headline": {{"en": "<=6 words", "ur": "<=6 words"}},
      "narration": {{"en": "1-2 sentences", "ur": "1-2 sentences"}},
      "keywords": {{"en": ["word"], "ur": ["لفظ"]}},
      "camera": "push_in|pan_left|pan_right|pull_out|drift|static"
    }}
  ]
}}

Rules:
- exactly {n_scenes} scenes, total narration about {seconds} seconds when spoken.
- plain factual explanation, no citations, no URLs, no invented numbers.
- Urdu must be Urdu script (never Roman Urdu) and must mean the same as English.
- first scene hooks, last scene recaps.
Topic: {topic}
"""


def generate_with_llm(llm: Any, topic: str, langs: Sequence[str], target_seconds: float,
                      palette: str = "auto") -> Story:
    n_scenes = max(3, min(8, int(round(target_seconds / 9.0))))
    prompt = PROMPT.format(n_scenes=n_scenes, seconds=int(target_seconds), topic=topic)
    out = llm(prompt, max_tokens=2048, temperature=0.7, top_p=0.9,
              stop=["```"]) if callable(llm) else llm.create_completion(prompt, max_tokens=2048)
    text = out["choices"][0]["text"] if isinstance(out, dict) else str(out)
    data = extract_json(text)
    scenes = []
    for i, sd in enumerate(data.get("scenes", [])):
        sd.setdefault("id", f"scene_{i + 1}")
        sd.setdefault("purpose", "explain")
        sd.setdefault("motif", "flow")
        sd.setdefault("elements", [
            {"type": "plate", "slot": "plate"},
            {"type": "process_chain", "slot": "stage",
             "params": {"nodes_en": ["step %d" % (i + 1)], "nodes_ur": ["مرحلہ"]}},
        ])
        sd.setdefault("actions", [{"action": "process"}])
        sd.setdefault("character", {"pose": "present", "slot": "char_left" if i % 2 == 0 else "char_right"})
        scenes.append(Scene.from_dict(sd))
    story = Story(
        topic=topic, world="generic", palette="violet" if palette == "auto" else palette,
        title=data.get("title", {"en": topic, "ur": topic}), scenes=scenes,
        languages=list(langs), generator="local-llm",
        warnings=["Script generated by a local LLM; review facts before publishing. "
                  "Visuals use the generic schematic world."],
    )
    validate_story(story, languages=langs)
    return story
